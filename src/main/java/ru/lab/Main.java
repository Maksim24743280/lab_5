package ru.lab;

import com.google.gson.Gson; // Импортируем основной класс библиотеки Gson для парсинга JSON
import com.google.gson.reflect.TypeToken; // Импортируем TypeToken для корректного определения типа коллекции List<ru.lab.Visitor> при чтении JSON

import java.io.FileReader; // Импортируем FileReader для чтения файла books.json с диска
import java.io.IOException; // Импортируем класс исключения IOException для обработки ошибок чтения файла
import java.io.Reader; // Импортируем базовый класс Reader для работы с текстовыми потоками ввода
import java.lang.reflect.Type; // Импортируем класс Type для передачи информации о типе списка в Gson
import java.nio.charset.StandardCharsets; // Импортируем стандартные кодировки, чтобы гарантировать чтение файла в UTF-8
import java.util.Comparator; // Импортируем интерфейс Comparator для настройки правил сортировки книг
import java.util.List; // Импортируем интерфейс List для работы со списками объектов
import java.util.Map; // Импортируем интерфейс Map для хранения результатов группировки (ключ-значение)
import java.util.stream.Collectors; // Импортируем утилитный класс Collectors для сборки элементов потока в коллекции и группировки

public class Main { // Объявляем главный класс программы

    public static void main(String[] args) { // Точка входа в программу — метод main

        Gson gson = new Gson(); // Создаем экземпляр класса Gson для преобразования JSON в Java-объекты

        List<Visitor> visitors; // Объявляем переменную для хранения списка посетителей, прочитанных из файла

        // Открываем файл books.json в блоке try-with-resources, чтобы поток чтения автоматически закрылся после работы
        try (Reader reader = new FileReader("books.json", StandardCharsets.UTF_8)) {

            // Создаем объект Type, который сообщает Gson, что корневой элемент JSON — это список объектов ru.lab.Visitor (List<ru.lab.Visitor>)
            Type visitorListType = new TypeToken<List<Visitor>>() {}.getType();

            // Читаем JSON из файла и преобразуем его в список объектов List<ru.lab.Visitor>
            visitors = gson.fromJson(reader, visitorListType);

        } catch (IOException e) { // Перехватываем ошибку, если файл books.json не найден или не может быть прочитан
            System.err.println("Ошибка при чтении файла books.json: " + e.getMessage()); // Выводим сообщение об ошибке в консоль
            return; // Завершаем выполнение программы, так как без исходных данных дальнейшая работа невозможна
        }

        // =========================================================================
        // ЗАДАНИЕ № 1. Вывести список посетителей и их количество
        // =========================================================================
        System.out.println("=== ЗАДАНИЕ № 1: Список посетителей и их количество ==="); // Выводим заголовок первого задания

        visitors.stream() // Преобразуем список посетителей в поток данных (Stream<ru.lab.Visitor>)
                .forEach(System.out::println); // Для каждого элемента потока вызываем метод println, выводя посетителя на экран

        long visitorsCount = visitors.stream() // Снова запускаем поток по списку посетителей
                .count(); // Подсчитываем общее количество элементов в потоке с помощью терминального метода count()

        System.out.println("Общее количество посетителей: " + visitorsCount); // Выводим итоговое количество посетителей
        System.out.println(); // Выводим пустую строку для визуального разделения заданий в консоли

        // =========================================================================
        // ЗАДАНИЕ № 2. Список и количество всех избранных книг без повторений
        // =========================================================================
        System.out.println("=== ЗАДАНИЕ № 2: Уникальные книги в избранном ==="); // Выводим заголовок второго задания

        List<Book> uniqueBooks = visitors.stream() // Создаем поток посетителей (Stream<ru.lab.Visitor>)
                .flatMap(visitor -> visitor.getFavoriteBooks().stream()) // Разворачиваем список книг каждого посетителя в один общий поток книг (Stream<ru.lab.Book>)
                .distinct() // Удаляем дубликаты книг (использует методы equals() и hashCode(), сгенерированные Lombok)
                .collect(Collectors.toList()); // Собираем уникальные книги обратно в список List<ru.lab.Book>

        uniqueBooks.forEach(System.out::println); // Выводим каждую уникальную книгу из полученного списка на экран

        long uniqueBooksCount = uniqueBooks.stream() // Создаем поток из списка уникальных книг
                .count(); // Подсчитываем количество уникальных книг через метод Stream API count()

        System.out.println("Количество уникальных книг: " + uniqueBooksCount); // Выводим количество уникальных книг
        System.out.println(); // Пустая строка для разделения вывода

        // =========================================================================
        // ЗАДАНИЕ № 3. Отсортировать и вывести список всех книг по году издания
        // =========================================================================
        System.out.println("=== ЗАДАНИЕ № 3: Книги, отсортированные по году издания ==="); // Выводим заголовок третьего задания

        List<Book> sortedBooks = visitors.stream() // Запускаем поток по списку посетителей
                .flatMap(visitor -> visitor.getFavoriteBooks().stream()) // Преобразуем потоки списков книг каждого посетителя в единый поток книг
                .sorted(Comparator.comparingInt(Book::getPublishingYear)) // Сортируем книги по возрастанию года издания, используя ссылку на геттер getPublishingYear
                .collect(Collectors.toList()); // Собираем отсортированный поток книг в список List<ru.lab.Book>

        sortedBooks.forEach(System.out::println); // Выводим отсортированный список книг на экран
        System.out.println(); // Пустая строка для разделения вывода

        // =========================================================================
        // ЗАДАНИЕ № 4. Проверить, есть ли у кого-то в избранном книга автора "Jane Austen"
        // =========================================================================
        System.out.println("=== ЗАДАНИЕ № 4: Поиск книг автора Jane Austen ==="); // Выводим заголовок четвертого задания

        boolean hasJaneAusten = visitors.stream() // Запускаем поток посетителей
                .flatMap(visitor -> visitor.getFavoriteBooks().stream()) // Получаем единый поток всех избранных книг всех посетителей
                .anyMatch(book -> "Jane Austen".equals(book.getAuthor())); // Проверяем, есть ли хотя бы одна книга, у которой поле author равно "Jane Austen"

        // Выводим результат проверки на экран (да/нет в зависимости от значения булевой переменной hasJaneAusten)
        System.out.println("Есть ли книга автора 'Jane Austen' в избранном: " + (hasJaneAusten ? "Да" : "Нет"));
        System.out.println(); // Пустая строка для разделения вывода

        // =========================================================================
        // ЗАДАНИЕ № 5. Максимальное число книг, добавленных одним посетителем в избранное
        // =========================================================================
        System.out.println("=== ЗАДАНИЕ № 5: Максимальное число избранных книг у одного посетителя ==="); // Выводим заголовок пятого задания

        int maxBooksCount = visitors.stream() // Запускаем поток по списку посетителей
                .mapToInt(visitor -> visitor.getFavoriteBooks().size()) // Преобразуем каждого посетителя в число (количество его любимых книг) в числовом потоке IntStream
                .max() // Находим максимальное значение в числовом потоке (возвращает OptionalInt)
                .orElse(0); // Если список посетителей оказался пустым, возвращаем значение по умолчанию — 0

        System.out.println("Максимальное количество избранных книг у одного посетителя: " + maxBooksCount); // Выводим найденный максимум
        System.out.println(); // Пустая строка для разделения вывода

        // =========================================================================
        // ЗАДАНИЕ № 6. Сообщения подписчикам (группировка и генерация SMS)
        // =========================================================================
        System.out.println("=== ЗАДАНИЕ № 6: SMS-сообщения для подписчиков ==="); // Выводим заголовок шестого задания

        // Шаг 1: Вычисляем среднее количество избранных книг по ВСЕМ посетителям библиотеки (согласно условию задачи)
        double averageBooks = visitors.stream() // Запускаем поток по всем посетителям
                .mapToInt(visitor -> visitor.getFavoriteBooks().size()) // Преобразуем каждого посетителя в количество его избранных книг
                .average() // Вычисляем среднее арифметическое значение (возвращает OptionalDouble)
                .orElse(0.0); // Если посетителей нет, берем 0.0 в качестве среднего значения

        System.out.println("Среднее количество книг по всем посетителям: " + averageBooks); // Выводим рассчитанное среднее значение для наглядности

        // Шаг 2: Фильтруем подписчиков и группируем их по тексту положенного им сообщения с помощью groupingBy()
        Map<String, List<Visitor>> groupedSubscribers = visitors.stream() // Запускаем поток по всем посетителям
                .filter(Visitor::isSubscribed) // Оставляем в потоке только тех посетителей, у которых subscribed == true (согласившихся на рассылку)
                .collect(Collectors.groupingBy(visitor -> { // Группируем подписчиков по категории (ключом Map будет текст SMS-сообщения)
                    int count = visitor.getFavoriteBooks().size(); // Получаем количество любимых книг текущего подписчика
                    if (count > averageBooks) { // Если книг у подписчика больше среднего по всем посетителям
                        return "you are a bookworm"; // Относим его к группе с сообщением "you are a bookworm"
                    } else if (count < averageBooks) { // Если книг у подписчика меньше среднего
                        return "read more"; // Относим его к группе с сообщением "read more"
                    } else { // Если количество книг в точности равно среднему значению
                        return "fine"; // Относим его к группе с сообщением "fine"
                    }
                }));

        // Шаг 3: Преобразуем сгруппированные данные в плоский список объектов ru.lab.SmsMessage
        List<SmsMessage> smsMessages = groupedSubscribers.entrySet().stream() // Создаем поток из пар (Категория сообщения -> Список посетителей) нашей Map
                .flatMap(entry -> entry.getValue().stream() // Для каждой категории берем список попавших в неё посетителей и разворачиваем в поток
                        .map(visitor -> new SmsMessage(visitor.getPhone(), entry.getKey()))) // Преобразуем каждого посетителя в объект ru.lab.SmsMessage с его телефоном и текстом группы
                .collect(Collectors.toList()); // Собираем все созданные объекты ru.lab.SmsMessage в единый итоговый список List<ru.lab.SmsMessage>

        // Шаг 4: Выводим сгенерированные SMS-сообщения на экран
        smsMessages.forEach(System.out::println); // Выводим каждое SMS-сообщение в консоль
    }
}
